def amendments_section(facts: Facts) -> str:
    return (
        "\n".join(
            ["## Protocol amendments", "", banner(facts), "", amendments_mod.text(facts.repo)]
        ).rstrip()
        + "\n"
    )


def manuscript(facts: Facts) -> str:
    """Methods, Results, the characteristics, amendments, funding, competing interests and data
    availability, in that order, with nothing after them: no Discussion, no Conclusion."""
    from strata.report import checklist as checklist_mod

    title = facts.project.get("title", "Systematic review")
    parts = [
        f"# {title}",
        "",
        banner(facts),
        "",
        methods(facts).replace(banner(facts) + "\n\n", "", 1),
        results(facts).replace(banner(facts) + "\n\n", "", 1),
        characteristics_markdown(facts.repo).replace("## ", "### ", 1),
    ]
    parts.append(amendments_section(facts).replace(banner(facts) + "\n\n", "", 1))
    for item_id, heading in (
        ("25", "Funding"),
        ("26", "Competing interests"),
        ("27", "Availability of data, code and other materials"),
    ):
        item = next(i for i in checklist_mod.build(facts) if i.id == item_id)
        body = item.content if item.status != checklist_mod.AUTHOR else f"[{item.content}]"
        parts.append(f"## {heading}\n\n{body}\n")
    return "\n".join(p if p.endswith("\n") else p + "\n" for p in parts)


def convert(markdown: str, fmt: str, *, title: str = "") -> bytes:
    """Markdown to `fmt` (`md` as is; `html`, `docx`, `latex` through pandoc)."""
    if fmt == "md":
        return markdown.encode("utf-8")
    if fmt not in MANUSCRIPT_FORMATS:
        raise PandocError(f"format must be one of {', '.join(MANUSCRIPT_FORMATS)}, got {fmt!r}")
    pandoc = shutil.which("pandoc")
    if pandoc is None:
        raise PandocError(
            f"--format {fmt} needs pandoc, which is not installed (https://pandoc.org/installing.html); --format md works without it"
        )
    target = {"html": "html5", "docx": "docx", "latex": "latex"}[fmt]
    with tempfile.TemporaryDirectory(prefix="strata-pandoc-") as tmp:
        out = Path(tmp) / f"out.{'tex' if fmt == 'latex' else fmt}"
        args = [pandoc, "-f", "gfm", "-t", target, "--standalone", "-o", str(out)]
        if title:
            args += ["--metadata", f"title={title}"]
        done = subprocess.run(
            args, input=markdown.encode("utf-8"), capture_output=True, timeout=120
        )
        if done.returncode != 0:
            raise PandocError(done.stderr.decode("utf-8", "replace").strip() or "pandoc failed")
        return out.read_bytes()
