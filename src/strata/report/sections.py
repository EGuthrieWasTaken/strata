def characteristics_rows(repo: Repo) -> tuple[list[str], list[list[str]]]:
    """One row per included study: its citation, year and every coding-form field."""
    from strata.extract import schema as schema_mod

    members = studies_mod.study_map(repo).members
    schema = schema_mod.load_schema(repo) if schema_mod.schema_exists(repo) else None
    names = [f["name"] for f in schema.fields] if schema else []
    labels = [f.get("label") or f["name"] for f in schema.fields] if schema else []
    consensus = {
        r["study"]: r
        for kind, _h, r, _p in extraction_records.all_records(repo)
        if kind == "consensus" and r.get("study") in members
    }
    records = records_mod.index_by_id(records_mod.read_records(repo))
    columns = ["Study", "Year", "Reports", *labels]
    rows = []
    for study in sorted(members, key=lambda s: _sort_key(repo, records, members[s])):
        first = records.get(record_id_for_report(members[study][0]), {})
        fields = (consensus.get(study) or {}).get("fields") or {}
        cells = [
            records_mod.short_citation(first),
            str(normalise_year(first.get("issued")) or ""),
            str(len(members[study])),
        ]
        for name in names:
            entry = fields.get(name)
            if not entry or entry.get("not_reported"):
                cells.append("NR" if entry else "")
                continue
            value = entry.get("value")
            text = (
                ", ".join(str(v) for v in value)
                if isinstance(value, list)
                else ("" if value is None else str(value))
            )
            cells.append(text + (f" {entry['unit']}" if entry.get("unit") else ""))
        rows.append(cells)
    keep = [j for j in range(len(columns)) if j < 3 or any(row[j] for row in rows)]
    return [columns[j] for j in keep], [[row[j] for j in keep] for row in rows]


def _sort_key(repo: Repo, records: dict[str, Any], reports: tuple[str, ...]) -> tuple[str, int]:
    first = records.get(record_id_for_report(reports[0]), {})
    return records_mod.short_citation(first), int(normalise_year(first.get("issued")) or 0)


def characteristics_markdown(repo: Repo, facts: Facts | None = None) -> str:
    columns, rows = characteristics_rows(repo)
    if not rows:
        return "## Characteristics of included studies\n\nNo study is included yet.\n"
    head = "| " + " | ".join(c.replace("|", "\\|") for c in columns) + " |"
    rule = "|" + "|".join("---" for _ in columns) + "|"
    body = [
        "| " + " | ".join(c.replace("|", "\\|").replace("\n", " ") for c in row) + " |"
        for row in rows
    ]
    lines = ["## Characteristics of included studies", ""]
    if facts is not None:
        lines += [banner(facts), ""]
    lines += [head, rule, *body, "", "NR: not reported."]
    return "\n".join(lines) + "\n"


