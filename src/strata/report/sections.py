def _analysis_methods(a: AnalysisFacts) -> str:
    spec = a.spec
    model, dep, include = spec.section("model"), spec.section("dependency"), spec.section("include")
    name = _measure(spec.measure)
    text = f"For analysis `{a.id}` ({spec.title}) the effect measure was the {name}. "
    if model["type"] == "random-effects":
        text += f"A random-effects model was fitted with the {model['tau2_estimator']} estimator of between-study variance"
        text += (
            " and Knapp-Hartung confidence intervals (with the standard error not allowed to fall below the Wald standard error)"
            if model["ci_method"] == "knapp-hartung"
            else " and Wald-type confidence intervals"
        )
        text += ". "
    else:
        text += "A common-effect model was fitted. "
    if include.get("filter"):
        text += f"Studies were eligible for this synthesis when `{include['filter']}`. "
    handling = dep.get("handling", "none")
    if handling == "aggregate":
        text += f"Studies contributing several effects were combined into one before pooling, assuming a within-study correlation of {dep.get('rho')}. "
    elif handling == "cluster-robust":
        text += f"Dependent effects were pooled with a random-effects model and cluster-robust variance estimation with the CR2 small-sample correction (assumed correlation {dep.get('rho')}). "
    elif handling == "multilevel":
        text += f"Dependent effects were pooled with a multilevel model (study and effect random effects, assumed correlation {dep.get('rho')}). "
    if model["type"] == "random-effects":
        text += "Heterogeneity was described with Q, I^2 (computed from Q), tau^2 with its Q-profile confidence interval, and a 95% prediction interval based on a t distribution with k - 2 degrees of freedom. "
    if spec.section("moderators"):
        text += (
            "Sources of heterogeneity were explored by meta-regression on "
            + _list([m["name"] for m in spec.section("moderators")])
            + ". "
        )
    if spec.section("publication_bias"):
        text += (
            "Small-study effects were examined with "
            + _list([BIAS_NAMES.get(b, b) for b in spec.section("publication_bias")])
            + "; these are sensitivity analyses and none corrects for publication bias. "
        )
    if spec.section("sensitivity"):
        text += (
            "Robustness was examined with "
            + _list(
                [SENSITIVITY_NAMES.get(s["type"], s["type"]) for s in spec.section("sensitivity")]
            )
            + ". "
        )
    if not spec.preregistered:
        text += "This analysis was not preregistered and is exploratory. "
    return text.strip()


def methods(facts: Facts) -> str:
    out = ["## Methods", "", banner(facts), ""]
    registry = facts.project.get("registry") or {}
    if registry:
        out += [
            "### Registration and protocol",
            "",
            "The review was registered ("
            + ", ".join(f"{k}: {v}" for k, v in registry.items())
            + "). The protocol, with its full history, is held in version control; amendments are reported below.",
            "",
        ]
    else:
        out += [
            "### Registration and protocol",
            "",
            "The protocol is held in version control with its full history; amendments are reported below. [The author should state whether the review was registered.]",
            "",
        ]
    active = [c for c in facts.criteria if c["status"] == "active"]
    if active:
        out += [
            "### Eligibility criteria",
            "",
            f"Eligibility was judged against the following criteria (version {facts.criteria_version}):",
            "",
        ]
        for kind in ("inclusion", "exclusion"):
            for c in active:
                if c["kind"] == kind:
                    out.append(f"- {kind.capitalize()}, {c['label']}: {c['definition']}")
        out.append("")
    if facts.searches or facts.other_imports:
        out += ["### Information sources and search", ""]
        sentences = [
            f"{s['database']} ({s['platform']}) was searched on {s['executed']}"
            for s in facts.searches
        ]
        sentences += [
            f"records from {VIA_NAMES.get(m['via'], m['via'])} were added on {m['imported']}"
            for m in facts.other_imports
        ]
        out += [
            _list(sentences)[0].upper()
            + _list(sentences)[1:]
            + ". The full search strategy for every database, as run, is reported in the supplement.",
            "",
        ]
    s = facts.screening
    reviewers = facts.reviewers("lead", "screener")
    out += ["### Selection process", ""]
    mode = s.get("mode", "single")
    sel = f"Records were screened at {_list(facts.stages)}"
    if mode == "single":
        sel += f" by one reviewer ({_list(reviewers)})"
    else:
        sel += (
            f" by two reviewers ({_list(reviewers)}) working independently"
            if s.get("blind_reviewers", True)
            else f" by two reviewers ({_list(reviewers)})"
        )
        if s.get("adjudicators"):
            sel += (
                f"; disagreements were resolved by adjudication ({_list(list(s['adjudicators']))})"
            )
    out += [
        sel
        + ". Duplicate records were identified and merged with strata's deduplication; no records were removed by other automation tools.",
        "",
    ]
    for stage, pairs in facts.irr.items():
        for p in pairs:
            out += [
                f"Agreement between {p.actor_a} and {p.actor_b} at {stage} was {p.raw_agreement:.0%} (Cohen's kappa {p.kappa:.2f}, n = {p.n}).",
                "",
            ]
    if facts.extraction_schema is not None:
        out += ["### Data collection", ""]
        who = _list(facts.reviewers("lead", "extractor"))
        if facts.extraction_mode == "dual":
            rate = facts.agreement or {}
            out += [
                f"Two reviewers ({who}) extracted data independently with a versioned coding form, recording a source for every value, and settled each difference with a recorded rationale; they agreed on {rate.get('agreed', 0)} of {rate.get('compared', 0)} compared items before reconciliation.",
                "",
            ]
        else:
            out += [
                f"One reviewer ({who}) extracted data with a versioned coding form, recording a source for every value.",
                "",
            ]
        if facts.extraction_schema.outcomes:
            out += ["Outcomes sought: " + _list(facts.extraction_schema.outcomes) + ".", ""]
    if facts.instrument is not None:
        i = facts.instrument
        out += [
            "### Risk of bias",
            "",
            f"Risk of bias was assessed with {i.name} (version {i.version})"
            + (
                " by two reviewers, independently, with differences reconciled"
                if facts.extraction_mode == "dual"
                else " by one reviewer"
            )
            + ". Where the instrument defines an algorithm for the overall judgement the suggestion was recorded, and each departure from it is recorded with a justification.",
            "",
        ]
    if facts.analyses:
        out += ["### Synthesis", ""]
        out += [_analysis_methods(a) + "\n" for a in facts.analyses]
        out += [
            f"Analyses were run with strata {facts.version}, whose estimators are validated against R's `metafor` and `clubSandwich` packages to a relative tolerance of 1e-8.",
            "",
        ]
    return "\n".join(out).rstrip() + "\n"


