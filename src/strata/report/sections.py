"""Generated manuscript material: Methods, Results, the characteristics table, risk of bias, and the
manuscript that assembles them (openspec:manuscript-generation).

The rules for generated prose (openspec:manuscript-generation#rules-for-generated-prose) are held
by construction: every section is marked as generated with the commit it came from; every number is
read from `estimates.json` (or the counts) and rounded to the precision the data supports (two
decimals for an effect size, whole percentages for I^2); no sentence makes a causal claim or leans
on statistical-significance language; the caveat of every guardrail that fired is carried into
Results; and there is no Discussion or Conclusion. `violations` checks a text against the
wording rules, and the tests run it over generated output.
"""

