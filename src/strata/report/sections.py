# --- helpers --------------------------------------------------------------------------------


def banner(facts: Facts) -> str:
    if facts.commit is None:
        where = "an uncommitted state of the repository"
    else:
        where = f"commit {facts.commit[:10]}" + (" plus uncommitted changes" if facts.dirty else "")
    return f"*Generated by strata {facts.version} from {where}. This is a draft for the author to check against the repository; it is not a substitute for reading it.*"


def _list(items: list[str]) -> str:
    if len(items) <= 1:
        return "".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


def _measure(measure: str) -> str:
    return MEASURE_NAMES.get(measure, measure)


def _p(value: float | None) -> str:
    if value is None:
        return "not available"
    return "p < 0.001" if value < 0.001 else f"p = {value:.3f}"


