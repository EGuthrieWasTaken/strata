# Wording the generated text must not contain (checked outside quoted material).
_BANNED = (
    r"\bsignificant(?:ly)?\b", r"\bnon-?significant\b", r"\bcaused?\b", r"\bcauses\b", r"\bcausal(?:ly)?\b",
    r"\bleads? to\b", r"\bled to\b", r"\bresulted? in\b", r"\bdue to\b", r"\bbecause\b", r"\bproves?\b",
    r"\bimproves?\b", r"\breduces?\b", r"\bincreases?\b", r"\beffective(?:ly)?\b", r"\bbeneficial\b",
    r"\bthe effect of\b",
)  # fmt: skip


def violations(text: str) -> list[str]:
    """Wording in generated prose that the rules forbid, ignoring quoted material (a rationale the
    author wrote is theirs)."""
    unquoted = re.sub(r'"[^"\n]*"', " ", text)
    unquoted = re.sub(r"`[^`\n]*`", " ", unquoted)
    return [m.group(0) for pattern in _BANNED for m in re.finditer(pattern, unquoted, re.I)]


