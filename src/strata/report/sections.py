_JUDGEMENT_STYLE = {
    "low": ("accent", "+"),
    "some-concerns": ("tint3", "?"),
    "high": ("accent2", "-"),
}


def _rob_cells(repo: Repo) -> tuple[list[str], list[tuple[str, dict[str, Any]]]]:
    instrument = rob_mod.load_instrument(repo)
    found = rob_mod.moderators(repo)
    members = studies_mod.study_map(repo).members
    records = records_mod.index_by_id(records_mod.read_records(repo))
    names = [d["id"] for d in instrument.domains]
    rows = []
    for study in sorted(found, key=lambda s: _sort_key(repo, records, members[s])):
        first = records.get(record_id_for_report(members[study][0]), {})
        rows.append((records_mod.short_citation(first), found[study]))
    return names, rows


def rob_markdown(repo: Repo, facts: Facts | None = None) -> str:
    try:
        names, rows = _rob_cells(repo)
    except rob_mod.RobError:
        return "## Risk of bias\n\nNo risk-of-bias instrument is recorded yet.\n"
    if not rows:
        return "## Risk of bias\n\nNo study has a reconciled risk-of-bias judgement yet.\n"
    columns = ["Study", *names, "Overall"]
    lines = ["## Risk of bias", ""]
    if facts is not None:
        lines += [banner(facts), ""]
    lines += ["| " + " | ".join(columns) + " |", "|" + "|".join("---" for _ in columns) + "|"]
    for citation, values in rows:
        cells = [str(values.get(f"rob.{n}") or "") for n in names] + [
            str(values.get("rob_overall") or "")
        ]
        lines.append("| " + " | ".join([citation, *cells]) + " |")
    return "\n".join(lines) + "\n"


def rob_svg(repo: Repo) -> bytes | None:
    """A traffic-light plot of the judgements: a symbol as well as a colour in every cell."""
    try:
        names, rows = _rob_cells(repo)
    except rob_mod.RobError:
        return None
    if not rows:
        return None
    columns = [*names, "overall"]
    cell, left, top = 26.0, 190.0, 60.0
    width = max(left + cell * len(columns) + 20, left + 3 * 140.0)  # room for the legend
    height = top + cell * len(rows) + 50
    canvas = cv.Canvas(
        width,
        height,
        "Risk of bias traffic-light plot",
        f"Risk-of-bias judgements for {len(rows)} studies across {len(columns)} domains: + low, ? some concerns, - high.",
    )
    for j, label in enumerate(columns):
        canvas.add(
            cv.Text(
                left + cell * j + cell / 2,
                top - 6,
                label,
                "ink",
                anchor="start",
                size=10,
                bold=True,
                rotate=-45,
            )
        )
    for i, (citation, values) in enumerate(rows):
        y = top + cell * i + cell / 2
        canvas.add(cv.Text(left - 8, y + 4, citation, "ink", anchor="end", size=10))
        for j, key in enumerate([*(f"rob.{n}" for n in names), "rob_overall"]):
            cls, symbol = _JUDGEMENT_STYLE.get(str(values.get(key)), ("muted", "?"))
            cx = left + cell * j + cell / 2
            canvas.add(
                cv.Circle(cx, y, 9, cls),
                cv.Text(cx, y + 4, symbol, "surface", anchor="middle", size=12, bold=True),
            )
    legend_y = height - 22
    for k, (judgement, (cls, symbol)) in enumerate(_JUDGEMENT_STYLE.items()):
        x = left + k * 140
        canvas.add(
            cv.Circle(x, legend_y, 7, cls),
            cv.Text(x, legend_y + 4, symbol, "surface", anchor="middle", size=10, bold=True),
            cv.Text(x + 12, legend_y + 4, judgement.replace("-", " "), "ink", size=10),
        )
    return canvas.render_svg().encode("utf-8")


