def _fresh(repo: Repo, analysis_id: str) -> bool:
    try:
        return analysis_run.results_state(repo, analysis_id) == "fresh"
    except ValueError:
        return False


def _analysis_results(repo: Repo, a: AnalysisFacts) -> str:
    e = a.estimates
    assert e is not None
    pooled = e["pooled"]
    first = pooled["coefficients"][0]
    name = _measure(e["measure"])
    parts = [
        f"For analysis `{a.id}`, across {e['k_studies']} studies ({e['k_effects']} effects), the pooled {name} was {first['estimate']:.2f} "
        f"(95% CI {first['ci_lb']:.2f} to {first['ci_ub']:.2f})."
    ]
    back = e.get("back_transformed")
    if back:
        parts.append(
            f"On the {back['scale']} scale this corresponds to {back['estimate']:.2f} (95% CI {back['ci_lb']:.2f} to {back['ci_ub']:.2f})."
        )
    het = pooled.get("heterogeneity")
    if het:
        parts.append(
            f"Between-study heterogeneity was tau = {het['tau']:.2f} (tau^2 = {het['tau2']:.2f}), I^2 = {het['I2']:.0f}%, Q({het['Q_df']}) = {het['Q']:.1f}, {_p(het.get('Q_p'))}."
        )
    pi = pooled.get("prediction_interval")
    if pi and pi.get("lb") is not None:
        parts.append(
            f"The 95% prediction interval, within which the true effect of a new study would be expected to lie, was {pi['lb']:.2f} to {pi['ub']:.2f}."
        )
    elif pi:
        parts.append(f"No prediction interval is reported: {pi['reason']}.")
    for c in pooled["coefficients"][1:]:
        parts.append(
            f"In meta-regression the coefficient for {c['name']} was {c['estimate']:.2f} (95% CI {c['ci_lb']:.2f} to {c['ci_ub']:.2f})."
        )
    if e.get("excluded"):
        counts = {why: len(ids) for why, ids in e["excluded"].items()}
        parts.append(
            "Effects left out of this analysis: "
            + "; ".join(f"{n} {why}" for why, n in sorted(counts.items()))
            + "."
        )
    bias = e.get("publication_bias") or {}
    for key in ("egger", "begg", "pet_peese", "trim_fill"):
        if key in bias:
            parts.append(bias[key]["interpretation"].rstrip(".") + ".")
    sens = e.get("sensitivity") or {}
    for sid, s in sorted(sens.items()):
        rows = s.get("results") or []
        if s.get("type") == "leave_one_out" and rows:
            lo, hi = min(r["estimate"] for r in rows), max(r["estimate"] for r in rows)
            parts.append(
                f"Omitting each study in turn gave pooled estimates from {lo:.2f} to {hi:.2f} (analysis {sid})."
            )
        elif s.get("type") == "influence_diagnostics":
            flagged = [r for r in rows if r.get("flags")]
            parts.append(
                f"{len(flagged)} effect(s) were flagged as potentially influential, none removed (analysis {sid})."
            )
        elif rows:
            parts.append(
                f"Analysis {sid} ({s['type'].replace('_', ' ')}) gave {len(rows)} result(s), reported in the supplement."
            )
    caveats = []
    for w in (a.run or {}).get("warnings", []):
        state = " (acknowledged)" if w.get("acknowledged") else ""
        caveats.append(f"{w['code']}{state}: {w.get('message') or 'see run.json'}")
    if caveats:
        parts.append("Caveats from the analysis guardrails: " + " ".join(caveats))
    if not a.spec.preregistered:
        parts.append("This analysis was not preregistered and is exploratory.")
    if not _fresh(repo, a.id):
        parts.append(
            "[These results are out of date with the data: run `strata analyze` before relying on them.]"
        )
    return " ".join(parts)


def results(facts: Facts) -> str:
    c, t = facts.counts, facts.counts.totals
    out = ["## Results", "", banner(facts), "", "### Study selection", ""]
    text = (
        f"The searches and other sources identified {t.identified} records. After removing {t.removed_before_screening} before screening "
        f"({t.duplicates_removed} duplicates), {t.records_screened} records were screened and {t.records_excluded_tiab} excluded. "
        f"Of {t.reports_sought} reports sought for retrieval, {t.reports_not_retrieved} could not be retrieved; {t.reports_assessed} were assessed for "
        f"eligibility and {t.reports_excluded_ft} excluded"
    )
    if c.exclusion_reasons:
        text += " (" + "; ".join(f"{r.label}, n = {r.count}" for r in c.exclusion_reasons) + ")"
    text += (
        f". In total, {c.studies_included} studies ({t.reports_included} reports) were included."
    )
    if not c.complete:
        text += " [Screening is not finished, so these counts will change.]"
    out += [text, ""]
    done = [a for a in facts.analyses if a.estimates]
    if done:
        out += ["### Synthesis", ""] + [_analysis_results(facts.repo, a) + "\n" for a in done]
    pending = [a.id for a in facts.analyses if not a.estimates]
    if pending:
        out += ["[Analyses not yet run: " + ", ".join(pending) + ".]", ""]
    return "\n".join(out).rstrip() + "\n"


