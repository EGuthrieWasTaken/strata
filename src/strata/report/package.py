"""The reproducibility package: `strata export package` (PRISMA 2020 item 27).

Implements openspec:manuscript-generation#reproducibility-package. It holds what the item asks to be
made available: the search strategies, the criteria with their full version history, the screening
decision log, the extraction data, the analysis specifications and results, the review data licence
and a README that names the commit it came from. It contains no full text: nothing under
`fulltext/` except the manifest of identifiers and versions, and no PDF anywhere, so it carries no
third-party copyrighted material. Like every generated file it is deterministic (sorted entries,
fixed timestamps), so the same commit packages to the same bytes.
"""

# ruff: noqa: E501  (the README and licence text are long literal strings)
from __future__ import annotations

import io
import zipfile
from pathlib import Path

from strata import __version__, gitio
from strata.core.repo import Repo

_INCLUDE = (
    "strata.toml",
    "protocol",
    "events",
    "extraction",
    "rob",
    "analysis",
    "derived",
    "reports",
    "fulltext/manifest.ndjson",
    "imports",
)
_NEVER_SUFFIXES = (".pdf", ".djvu", ".epub")
_FIXED_TIME = (1980, 1, 1, 0, 0, 0)  # the earliest a ZIP can say: no timestamps

LICENSE_HINT = "set one first, for example: strata config project.license CC-BY-4.0"


class PackageError(ValueError):
    pass


def data_license(repo: Repo) -> str:
    license_id = str(repo.config.get("project", {}).get("license") or "").strip()
    if not license_id:
        raise PackageError(f"no review data licence is declared (project.license); {LICENSE_HINT}")
    return license_id


def _wanted(relative: Path) -> bool:
    parts = relative.parts
    if relative.suffix.lower() in _NEVER_SUFFIXES or ".strata" in parts or ".git" in parts:
        return False
    # The exports as downloaded are publisher metadata the package has no need of.
    return not (parts[0] == "imports" and "raw" in parts[1:])


def members(repo: Repo) -> list[Path]:
    """The files that go in the package, as repository-relative paths, sorted."""
    found: set[Path] = set()
    for entry in _INCLUDE:
        path = repo.path(*entry.split("/"))
        if path.is_file():
            found.add(Path(entry))
        elif path.is_dir():
            found.update(p.relative_to(repo.root) for p in path.rglob("*") if p.is_file())
    return sorted(p for p in found if _wanted(p))


def _readme(repo: Repo, license_id: str, files: list[Path]) -> str:
    try:
        commit = gitio.current_commit(repo.root)
    except gitio.GitError:
        commit = "(not a git checkout)"
    title = repo.config.get("project", {}).get("title", "Systematic review")
    remote = gitio.get_config(repo.root, "remote.origin.url") or "(no remote configured)"
    top = sorted({p.parts[0] if len(p.parts) > 1 else p.name for p in files})
    lines = [
        f"# Reproducibility package: {title}",
        "",
        f"Generated by strata {__version__} from commit `{commit}` of {remote}.",
        "",
        "This archive holds the materials PRISMA 2020 item 27 asks authors to make available: the search "
        "strategies (`protocol/searches/`), the eligibility criteria with their version history "
        "(`protocol/criteria.yaml`, `events/criteria/`), the screening decision log (`events/`), the "
        "extracted data and coding form (`extraction/`), risk-of-bias assessments (`rob/`), the analysis "
        "specifications and their results (`analysis/`), the derived counts (`derived/`) and the generated "
        "reports (`reports/`).",
        "",
        "It contains no full texts and no PDF: `fulltext/manifest.ndjson` lists which documents were "
        "used, by identifier and version, so a reader can obtain their own copy.",
        "",
        f"The review data are made available under the licence `{license_id}` (see `LICENSE-DATA.txt`).",
        "",
        "## Contents",
        "",
        *[f"- `{name}`" for name in top],
        "",
        f"{len(files)} files in all. To rebuild the results, clone the repository at the commit above and "
        "run `strata analyze --all`.",
        "",
    ]
    return "\n".join(lines)


def _license_text(license_id: str) -> str:
    return (
        f"The data in this package (the search strategies, the screening decisions, the extracted data, the "
        f"analysis specifications and the results) are made available under the licence identified by the "
        f"SPDX identifier\n\n    {license_id}\n\nThe licence text is at https://spdx.org/licenses/{license_id}.html\n"
        "Bibliographic metadata and any quotations remain the property of their publishers and authors.\n"
    )


def build(repo: Repo) -> bytes:
    license_id = data_license(repo)
    files = members(repo)
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        extra = {
            "README.md": _readme(repo, license_id, files).encode("utf-8"),
            "LICENSE-DATA.txt": _license_text(license_id).encode("utf-8"),
        }
        entries = {p.as_posix(): p for p in files}
        for name in sorted({*entries, *extra}):
            info = zipfile.ZipInfo(name, date_time=_FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            data = extra[name] if name in extra else repo.path(*name.split("/")).read_bytes()
            archive.writestr(info, data)
    return buffer.getvalue()
