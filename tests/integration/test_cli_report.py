"""`strata report`: every section, the commit it makes, and the refusals (M5)."""

# ruff: noqa: E501
from __future__ import annotations

import json
import shutil
from pathlib import Path
from typing import Any

import pytest
from typer.testing import CliRunner

from strata import gitio
from strata.cli.main import EXIT_OK, EXIT_USAGE, EXIT_VALIDATION, app
from strata.core.repo import Repo
from strata.report import sections
from tests.unit._m5 import finished_review, full_review

runner = CliRunner()
WHY = ("--why", "Generating the report for the review record.")


def _cli(repo: Repo, *args: str, code: int = EXIT_OK) -> Any:
    result = runner.invoke(app, [*WHY, "-C", str(repo.root), *args])
    assert result.exit_code == code, result.output
    return result


def _commit_all(repo: Repo) -> None:
    gitio.add_all(repo.root)
    if gitio.is_dirty(repo.root):
        gitio.commit(repo.root, "test: fixture\n\nStrata-Op: test\nStrata-Actor: ethan")


@pytest.fixture
def review(tmp_path: Path) -> Repo:
    repo, _ = full_review(tmp_path)
    _commit_all(repo)
    return repo


def test_each_section_is_written_to_reports_and_committed(review: Repo) -> None:
    for section in ("methods", "results", "characteristics", "amendments"):
        before = len(gitio.log(review.root))
        _cli(review, "report", section)
        path = review.path("reports", f"{section}.md")
        assert path.is_file() and "Generated by strata" in path.read_text()
        assert len(gitio.log(review.root)) == before + 1
        body = gitio.run(["log", "-1", "--format=%B"], cwd=review.root).stdout
        assert "Strata-Op: report" in body and f"generated the {section} report" in body
        assert not gitio.is_dirty(review.root)


def test_the_generated_text_is_marked_with_the_commit_it_came_from(review: Repo) -> None:
    _cli(review, "report", "results", "--out", "-")
    head = gitio.current_commit(review.root)[:10]
    text = _cli(review, "report", "results", "--out", "-").output
    assert f"from commit {head}" in text and "uncommitted" not in text


def test_the_checklist_is_written_and_its_status_counted(review: Repo) -> None:
    _cli(review, "report", "checklist")
    text = review.path("reports", "prisma-checklist.md").read_text()
    assert "# PRISMA 2020 checklist" in text and "CC BY 4.0" in text
    status = json.loads(_cli(review, "--json", "report", "checklist", "--status").output)
    assert status["items"] == 42 and "22" in status["needs_author"]
    human = _cli(review, "report", "checklist", "--status").output
    assert "auto-filled" in human and "Still yours" in human


def test_risk_of_bias_writes_a_table_and_a_traffic_light_plot(review: Repo) -> None:
    result = _cli(review, "report", "rob")
    flat = result.output.replace("\n", "")
    assert "rob.md" in flat and "rob-traffic-light.svg" in flat
    assert review.path("reports", "rob-traffic-light.svg").read_bytes().startswith(b"<svg")
    assert "| Study | D1 |" in review.path("reports", "rob.md").read_text()


def test_the_characteristics_table_exports_to_tsv(review: Repo) -> None:
    _cli(review, "report", "characteristics", "--format", "csv")
    lines = review.path("reports", "characteristics.tsv").read_text().splitlines()
    assert lines[0].startswith("Study\tYear\tReports") and len(lines) == 11


def test_the_manuscript_assembles_without_a_discussion(review: Repo) -> None:
    _cli(review, "report", "manuscript")
    text = review.path("reports", "manuscript.md").read_text()
    assert "## Methods" in text and "## Results" in text and "## Protocol amendments" in text
    assert "Discussion" not in text and "Conclusion" not in text
    assert sections.violations(text) == []


@pytest.mark.skipif(shutil.which("pandoc") is None, reason="pandoc is not installed")
def test_the_manuscript_exports_through_pandoc(review: Repo) -> None:
    _cli(review, "report", "manuscript", "--format", "docx")
    assert review.path("reports", "manuscript.docx").read_bytes()[:2] == b"PK"
    _cli(review, "report", "manuscript", "--format", "latex")
    assert "\\begin{document}" in review.path("reports", "manuscript.tex").read_text()
    _cli(review, "report", "manuscript", "--format", "html")
    assert "<h2" in review.path("reports", "manuscript.html").read_text()


def test_pandoc_missing_is_a_usage_error(review: Repo, monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(shutil, "which", lambda name: None)
    result = _cli(review, "report", "manuscript", "--format", "docx", code=EXIT_USAGE)
    assert "needs pandoc" in result.output
    assert not review.path("reports", "manuscript.docx").exists()


def test_a_discussion_is_refused_and_an_unknown_section_lists_the_real_ones(review: Repo) -> None:
    before = (
        sorted(p.name for p in review.path("reports").iterdir())
        if review.path("reports").exists()
        else []
    )
    refused = _cli(review, "report", "discussion", code=EXIT_USAGE)
    assert "does not generate a Discussion or Conclusion" in refused.output.replace("\n", " ")
    _cli(review, "report", "conclusions", code=EXIT_USAGE)
    unknown = _cli(review, "report", "abstract", code=EXIT_USAGE)
    for section in sections.SECTIONS:
        assert section in unknown.output
    after = (
        sorted(p.name for p in review.path("reports").iterdir())
        if review.path("reports").exists()
        else []
    )
    assert after == before


def test_bad_options_are_usage_errors(review: Repo) -> None:
    _cli(review, "report", "methods", "--status", code=EXIT_USAGE)
    _cli(review, "report", "methods", "--format", "pdf", code=EXIT_USAGE)
    _cli(review, "report", "methods", "--format", "csv", code=EXIT_USAGE)
    _cli(review, "report", "rob", "--format", "csv", code=EXIT_USAGE)
    _cli(review, "report", "rob", "--out", "-", code=EXIT_USAGE)


def test_broken_counts_stop_every_report_but_amendments(tmp_path: Path) -> None:
    repo, _ = finished_review(tmp_path)
    _commit_all(repo)
    path = repo.path("records", "records.ndjson")
    rows = [json.loads(line) for line in path.read_text().splitlines()]
    stray = json.loads(json.dumps(rows[0]))
    stray["id"], stray["strata"]["canonical_key"] = "rec_" + "0" * 16, "sig:stray"
    path.write_text("\n".join(json.dumps(r) for r in [*rows, stray]) + "\n", encoding="utf-8")
    for section in ("methods", "results", "checklist", "manuscript"):
        failed = _cli(repo, "report", section, code=EXIT_VALIDATION)
        assert "E_COUNT_RECONCILE" in failed.output
    _cli(repo, "report", "amendments")


def test_json_output_names_the_files(review: Repo) -> None:
    out = json.loads(_cli(review, "--json", "report", "methods").output)
    assert out["section"] == "methods" and out["written"][0].endswith("methods.md")
