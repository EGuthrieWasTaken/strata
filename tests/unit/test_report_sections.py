# --- conversion -----------------------------------------------------------------------------


def test_markdown_is_returned_as_is_and_unknown_formats_refused() -> None:
    assert sections.convert("# T\n", "md") == b"# T\n"
    with pytest.raises(sections.PandocError, match="format must be one of"):
        sections.convert("# T\n", "pdf")


def test_missing_pandoc_is_a_specific_error(monkeypatch: pytest.MonkeyPatch) -> None:
    monkeypatch.setattr(shutil, "which", lambda name: None)
    with pytest.raises(sections.PandocError, match="needs pandoc"):
        sections.convert("# T\n", "docx")


@pytest.mark.skipif(shutil.which("pandoc") is None, reason="pandoc is not installed")
def test_pandoc_produces_html_docx_and_latex(tmp_path: Path) -> None:
    repo, _ = full_review(tmp_path)
    markdown = sections.manuscript(_facts(repo))
    html = sections.convert(markdown, "html", title="T").decode()
    assert "<h2" in html and "Methods" in html and "pooled standardised mean difference" in html
    assert sections.convert(markdown, "docx", title="T")[:2] == b"PK"
    latex = sections.convert(markdown, "latex", title="T").decode()
    assert "\\begin{document}" in latex and "Methods" in latex
