def _facts(repo):  # type: ignore[no-untyped-def]
    return facts_mod.collect(repo)


def _commit(repo) -> str:  # type: ignore[no-untyped-def]
    gitio.add_all(repo.root)
    gitio.commit(repo.root, "test: fixture\n\nStrata-Op: test\nStrata-Actor: ethan")
    return gitio.current_commit(repo.root)


# --- the rules ------------------------------------------------------------------------------


def test_every_section_is_marked_as_generated_with_its_commit(tmp_path: Path) -> None:
    repo, _ = full_review(tmp_path)
    commit = _commit(repo)
    facts = _facts(repo)
    for text in (
        sections.methods(facts), sections.results(facts), sections.amendments_section(facts),
        sections.characteristics_markdown(repo, facts), sections.rob_markdown(repo, facts),
    ):  # fmt: skip
        assert f"Generated by strata {facts.version} from commit {commit[:10]}" in text
        assert "draft for the author" in text
    # Work not yet committed is said to be so.
    edited, _ = full_review(tmp_path / "x")
    assert "plus uncommitted changes" in sections.banner(_facts(edited))


def test_numbers_are_taken_from_estimates_json_at_the_precision_the_data_supports(
    tmp_path: Path,
) -> None:
    repo, _ = full_review(tmp_path)
    estimates = json.loads(
        repo.path("analysis", "results", "primary", "estimates.json").read_text()
    )
    first = estimates["pooled"]["coefficients"][0]
    het = estimates["pooled"]["heterogeneity"]
    text = sections.results(_facts(repo))
    assert (
        f"the pooled standardised mean difference was {first['estimate']:.2f} (95% CI {first['ci_lb']:.2f} to {first['ci_ub']:.2f})"
        in text
    )
    assert f"I^2 = {het['I2']:.0f}%" in text and f"Q({het['Q_df']}) = {het['Q']:.1f}" in text
    assert not re.search(r"I\^2 = \d+\.\d", text)  # whole percentages
    pi = estimates["pooled"]["prediction_interval"]
    assert f"was {pi['lb']:.2f} to {pi['ub']:.2f}" in text
    assert re.search(r"estimate[s]? from -?\d\.\d\d to -?\d\.\d\d", text)  # leave-one-out range


def test_generated_prose_avoids_causal_and_significance_language(tmp_path: Path) -> None:
    repo, _ = full_review(tmp_path)
    facts = _facts(repo)
    generated = [
        sections.methods(facts),
        sections.results(facts),
        sections.manuscript(facts),
        sections.amendments_section(facts),
    ]
    for text in generated:
        assert sections.violations(text) == [], text
    assert "significant" not in "".join(generated).lower().replace("clinically", "")


def test_the_violation_check_catches_the_wording_it_exists_for() -> None:
    assert sections.violations("The effect was significant.") == ["significant"]
    assert sorted(
        sections.violations("Spacing improves recall because it reduces forgetting.")
    ) == [
        "because",
        "improves",
        "reduces",
    ]
    assert sections.violations("This led to better outcomes; the effect of spacing was large.")
    assert sections.violations('The author wrote "this caused harm" and `significant`.') == []
    assert (
        sections.violations(
            "The pooled standardised mean difference was 0.38 (95% CI 0.28 to 0.48)."
        )
        == []
    )


def test_a_guardrail_that_fired_is_a_caveat_in_the_results(tmp_path: Path) -> None:
    repo, _ = full_review(tmp_path)
    run_path = repo.path("analysis", "results", "primary", "run.json")
    run = json.loads(run_path.read_text())
    run["warnings"].append(
        {
            "code": "k-lt-10-bias-tests",
            "message": "Publication-bias tests are underpowered with fewer than 10 studies (computed with --force; results are labelled underpowered).",
            "acknowledged": False,
            "forced": True,
        }
    )
    run["warnings"].append(
        {
            "code": "exploratory",
            "message": "Not preregistered.",
            "acknowledged": True,
            "forced": False,
        }
    )
    run_path.write_text(json.dumps(run), encoding="utf-8")
    text = sections.results(_facts(repo))
    assert "k-lt-10-bias-tests: Publication-bias tests are underpowered" in text
    assert "high-heterogeneity: I^2 = " in text and "exploratory (acknowledged)" in text


def test_the_manuscript_has_no_discussion_and_nothing_after_the_data_statement(
    tmp_path: Path,
) -> None:
    repo, _ = full_review(tmp_path)
    text = sections.manuscript(_facts(repo))
    headings = re.findall(r"^#{1,3} (.+)$", text, re.M)
    assert not any(re.search(r"discussion|conclusion", h, re.I) for h in headings)
    assert headings[0] == repo.config["project"]["title"]
    for expected in (
        "Methods",
        "Results",
        "Protocol amendments",
        "Funding",
        "Competing interests",
        "Availability of data, code and other materials",
    ):
        assert expected in headings
    assert headings[-1] == "Availability of data, code and other materials"
    assert "[No funding is recorded" in text  # an author's gap is marked, not invented


